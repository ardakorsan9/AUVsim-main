function plot_simulation_results(path, vehicle_path, times, velocities, angular_velocities, orientations, path_params, sim_params, yaw_refs, pitch_refs, u_refs)
    % Plot the final simulation results once the numerical run is complete.
    % path_params: structure with path-generation parameters.
    % sim_params: structure with simulation settings such as dt and total_time.

    % Use logged references instead of path tangents
    yaw_ref = yaw_refs;
    pitch_ref = pitch_refs;

    average_speed = mean(sqrt(sum(velocities.^2, 2)));
    final_speed = norm(velocities(end, :));

    % Figure 1: 3D reference vs actual path
    figure('Name', 'AUV Path Comparison', 'NumberTitle', 'off');
    plot3(path(:, 1), path(:, 2), path(:, 3), 'k--', 'LineWidth', 1.4);
    hold on;
    plot3(vehicle_path(:, 1), vehicle_path(:, 2), vehicle_path(:, 3), 'b-', 'LineWidth', 1.8);
    scatter3(path(1, 1), path(1, 2), path(1, 3), 100, 'g', 'filled', 'DisplayName', 'Start Point');
    scatter3(path(end, 1), path(end, 2), path(end, 3), 100, 'r', 'filled', 'DisplayName', 'Target Point');
    grid on;
    axis equal;
    xlabel('X Position (m)');
    ylabel('Y Position (m)');
    zlabel('Z Position (m)');
    title('3D Path: Reference vs. Actual Vehicle Track');
    legend('Reference Path', 'Executed Vehicle Path', 'Start Point', 'Target Point', 'Location', 'best');

    % Figure 2: 2D top-down and summary information
    figure('Name', 'AUV Path and Simulation Summary', 'NumberTitle', 'off');
    subplot(2, 1, 1);
    plot(path(:, 1), path(:, 2), 'k--', 'LineWidth', 1.5);
    hold on;
    plot(vehicle_path(:, 1), vehicle_path(:, 2), 'b-', 'LineWidth', 1.8);
    scatter(path(1, 1), path(1, 2), 80, 'g', 'filled');
    scatter(path(end, 1), path(end, 2), 80, 'r', 'filled');
    grid on;
    axis equal;
    xlabel('X Position (m)');
    ylabel('Y Position (m)');
    title('2D Top-Down Path Comparison');
    legend('Reference Path', 'Executed Path', 'Start', 'End', 'Location', 'best');

    subplot(2, 1, 2);
    axis off;
    text(0, 0.95, 'Simulation Summary', 'FontSize', 12, 'FontWeight', 'bold');
    if strcmp(path_params.type, '3d_straight_line')
        annotation_text = sprintf([...
            'Start Point: [%.2f, %.2f, %.2f]\n'...
            'Reference Path Type: %s\n'...
            'Yaw Reference: computed from path tangents\n'...
            'Pitch Reference: computed from path tangents\n'...
            'Simulation dt: %.3f s\n'...
            'Total Simulation Time: %.2f s\n'...
            'Average Vehicle Speed: %.2f m/s\n'...
            'Final Vehicle Speed: %.2f m/s\n'...
            'Path Generation Parameters:\n'...
            '  - type = %s\n'...
            '  - description = %s\n'...
            '  - num_points = %d\n'], ...
            sim_params.start_position(1), sim_params.start_position(2), sim_params.start_position(3), ...
            sim_params.reference_path_type, sim_params.dt, sim_params.total_time, ...
            average_speed, final_speed, ...
            path_params.type, path_params.description, ...
            path_params.num_points);
    else
        annotation_text = sprintf([...
            'Start Point: [%.2f, %.2f, %.2f]\n'...
            'Reference Path Type: %s\n'...
            'Yaw Reference: computed from path tangents\n'...
            'Pitch Reference: computed from path tangents\n'...
            'Simulation dt: %.3f s\n'...
            'Total Simulation Time: %.2f s\n'...
            'Average Vehicle Speed: %.2f m/s\n'...
            'Final Vehicle Speed: %.2f m/s\n'...
            'Path Generation Parameters:\n'...
            '  - type = %s\n'...
            '  - description = %s\n'...
            '  - radius = %.2f\n'...
            '  - pitch = %.2f\n'...
            '  - num_turns = %d\n'...
            '  - num_points = %d\n'...
            '  - lookahead_distance = %.2f m\n'], ...
            sim_params.start_position(1), sim_params.start_position(2), sim_params.start_position(3), ...
            sim_params.reference_path_type, sim_params.dt, sim_params.total_time, ...
            average_speed, final_speed, ...
            path_params.type, path_params.description, ...
            path_params.radius, path_params.pitch, path_params.num_turns, path_params.num_points, ...
            path_params.lookahead_distance);
    end

    text(0, 0.02, annotation_text, 'FontSize', 10, 'Interpreter', 'none');

    % Figure 3: Velocities and orientations
    figure('Name', 'AUV Motion Overview', 'NumberTitle', 'off');
    subplot(3, 1, 1);
    plot(times, velocities(:, 1), 'b', times, velocities(:, 2), 'g', times, velocities(:, 3), 'r', 'LineWidth', 1.2);
    grid on;
    xlabel('Time (s)');
    ylabel('Velocity (m/s)');
    title('Body-Frame Velocities');
    legend('u (surge)', 'v (sway)', 'w (heave)', 'Location', 'best');

    physical_pitch = -orientations(:, 2);
    subplot(3, 1, 2);
    plot(times, rad2deg(physical_pitch), 'g', times, rad2deg(wrapToPi(orientations(:, 3))), 'b', 'LineWidth', 1.2);
    grid on;
    xlabel('Time (s)');
    ylabel('Angle (deg)');
    title('Actual Pitch and Yaw');
    legend('\theta (pitch)', '\psi (yaw)', 'Location', 'best');

    subplot(3, 1, 3);
        plot(times, rad2deg(pitch_ref), '--k', times, rad2deg(yaw_ref), ':k', ...
            times, rad2deg(physical_pitch), 'g', times, rad2deg(wrapToPi(orientations(:, 3))), 'b', 'LineWidth', 1.2);
    grid on;
    xlabel('Time (s)');
    ylabel('Reference / Actual Angle (deg)');
    title('Reference vs Actual Attitude');
    legend('Pitch Reference', 'Yaw Reference', 'Pitch Actual', 'Yaw Actual', 'Location', 'best');
end
