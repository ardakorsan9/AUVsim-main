function entry = build_entry(category_id, label, family, artifact_kind, source_schema, artifact_path, units)
    entry = struct();
    entry.category_id = category_id;
    entry.label = label;
    entry.family = family;
    entry.artifact_kind = artifact_kind;
    entry.source_schema = source_schema;
    entry.artifact_path = artifact_path;
    entry.units = units;
end

function units = nominal_units()
    units = struct( ...
        'duration_s', 's', ...
        'dt', 's', ...
        'seed', 'unitless', ...
        'mean_cross_track', 'm', ...
        'max_cross_track', 'm', ...
        'mean_yaw_err_deg', 'deg', ...
        'mean_pitch_err_deg', 'deg', ...
        'pitch_chatter_dps', 'deg/s', ...
        'theta_pp_deg', 'deg', ...
        'pct_samples_overrun', 'percent');
end

function units = bounded_current_units()
    units = nominal_units();
    units.Vc_ned = 'm/s';
end

function units = sensor_units()
    units = nominal_units();
    units.nav_dt_base = 's';
    units.imu_gyro_sigma_rad_s = 'rad/s';
    units.imu_accel_sigma_mps2 = 'm/s^2';
    units.depth_sigma_m = 'm';
    units.rmse_depth_m = 'm';
    units.rmse_yaw_deg = 'deg';
    units.avail_pct = 'percent';
end

function units = actuator_units()
    units = nominal_units();
    units.de_max_deg = 'deg';
    units.dr_max_deg = 'deg';
    units.rate_dps = 'deg/s';
    units.sat_frac = 'unitless';
    units.deadband_deg = 'deg';
    units.elevator_mag_sat_pct = 'percent';
    units.rudder_mag_sat_pct = 'percent';
end

function units = roll_units(contract)
    units = struct( ...
        'duration_s', 's', ...
        'dt', 's', ...
        'seed', 'unitless', ...
        'runtime_s', 's');
    thr = contract.screening.threshold_units;
    thr_fields = fieldnames(thr);
    for i = 1:numel(thr_fields)
        units.(thr_fields{i}) = thr.(thr_fields{i});
    end
    met = contract.metrics.units;
    met_fields = fieldnames(met);
    for i = 1:numel(met_fields)
        units.(met_fields{i}) = met.(met_fields{i});
    end
end
