function out = auv_simulation_category_registry(request, category_id)
%AUV_SIMULATION_CATEGORY_REGISTRY  Read-only category registry for AUV V1 artifacts.
%   registry = auv_simulation_category_registry()
%   ids = auv_simulation_category_registry('categories')
%   names = auv_simulation_category_registry('declared_metrics', category_id)
%   entry = auv_simulation_category_registry('resolve', category_id)
%   entry = auv_simulation_category_registry(category_id)

    if nargin >= 1 && ischar(request) && strcmpi(request, 'categories')
        out = category_ids();
        return;
    end

    if nargin >= 2 && ischar(request) && strcmpi(request, 'resolve')
        out = resolve_category(category_id);
        return;
    end

    if nargin >= 2 && ischar(request) && strcmpi(request, 'declared_metrics')
        out = declared_metrics(category_id);
        return;
    end

    if nargin == 1 && ischar(request) && ~strcmpi(request, 'categories')
        out = resolve_category(request);
        return;
    end

    registry = struct();
    registry.schema = 'auv_v1_simulation_category_registry_v1';
    registry.version = '1.0.0';
    registry.matlab_release = 'R2025b';
    registry.contract_schema = 'auv_v1_shared_result_contract_v1';
    registry.contract_version = '1.0.0';
    registry.categories = build_category_table();
    out = registry;
end

function ids = category_ids()
    ids = { ...
        'nominal', ...
        'bounded_current', ...
        'sensor_noise_dropout', ...
        'actuator_limits', ...
        'passive_roll_stress', ...
        'roll_rate_solution_audit'};
end

function names = declared_metrics(category_id)
    entry = resolve_category(category_id);
    names = sort(fieldnames(entry.units));
end

function entry = resolve_category(category_id)
    if nargin < 1 || isempty(category_id) || ~ischar(category_id) && ~isstring(category_id)
        error('auv_simulation_category_registry:InvalidCategory', ...
            'category_id must be a non-empty string');
    end
    category_id = char(category_id);
    table = build_category_table();
    for i = 1:numel(table)
        if strcmp(table(i).category_id, category_id)
            entry = table(i);
            return;
        end
    end
    error('auv_simulation_category_registry:UnknownCategory', ...
        'unknown simulation category: %s', category_id);
end

