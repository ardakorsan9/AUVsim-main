function out = auv_result_contract(request)
%AUV_RESULT_CONTRACT  Fixed AUV V1 shared simulation result contract (R2025b).
%   contract = auv_result_contract()
%   template = auv_result_contract('template')
%   Defines required top-level sections, field units, and shape conventions for
%   meta, time, truth, sensors, commands, actuators, metrics, screening, and
%   provenance. Roll-artifact rollups may leave time-series sections empty.

    if nargin >= 1 && strcmpi(request, 'template')
        out = build_result_template();
        return;
    end

    contract = struct();
    contract.schema = 'auv_v1_shared_result_contract_v1';
    contract.version = '1.0.0';
    contract.matlab_release = 'R2025b';

    contract.required_sections = { ...
        'meta', 'time', 'truth', 'sensors', 'commands', 'actuators', ...
        'metrics', 'screening', 'provenance'};

    contract.meta = struct( ...
        'required_fields', {{ ...
            'schema', 'contract_version', 'certified', 'source_schema', ...
            'scenario', 'mode', 'seed', 'artifact_kind'}}, ...
        'certified_must_be', false);

    contract.time = struct( ...
        'required_fields', {{'t_s', 'dt_s', 'n_samples'}}, ...
        'units', struct('t_s', 's', 'dt_s', 's'), ...
        't_s_orientation', 'column', ...
        'allow_empty_series', true);

    contract.truth = struct( ...
        'required_fields', {{ ...
            'position_ned_m', 'attitude_rad', 'velocity_body_mps', 'rates_body_rps'}}, ...
        'units', struct( ...
            'position_ned_m', 'm', ...
            'attitude_rad', 'rad', ...
            'velocity_body_mps', 'm/s', ...
            'rates_body_rps', 'rad/s'), ...
        'column_counts', struct( ...
            'position_ned_m', 3, ...
            'attitude_rad', 3, ...
            'velocity_body_mps', 3, ...
            'rates_body_rps', 3), ...
        'allow_empty_series', true);

    contract.sensors = struct( ...
        'required_fields', {{ ...
            'attitude_rad', 'angular_rate_body_rps', 'depth_m'}}, ...
        'units', struct( ...
            'attitude_rad', 'rad', ...
            'angular_rate_body_rps', 'rad/s', ...
            'depth_m', 'm'), ...
        'column_counts', struct( ...
            'attitude_rad', 3, ...
            'angular_rate_body_rps', 3, ...
            'depth_m', 1), ...
        'allow_empty_series', true);

    contract.commands = struct( ...
        'required_fields', {{'elevator_rad', 'rudder_rad', 'thrust_n'}}, ...
        'units', struct( ...
            'elevator_rad', 'rad', ...
            'rudder_rad', 'rad', ...
            'thrust_n', 'N'), ...
        'column_counts', struct( ...
            'elevator_rad', 1, ...
            'rudder_rad', 1, ...
            'thrust_n', 1), ...
        'allow_empty_series', true);

    contract.actuators = struct( ...
        'required_fields', {{'applied_elevator_rad', 'applied_rudder_rad'}}, ...
        'units', struct( ...
            'applied_elevator_rad', 'rad', ...
            'applied_rudder_rad', 'rad'), ...
        'column_counts', struct( ...
            'applied_elevator_rad', 1, ...
            'applied_rudder_rad', 1), ...
        'allow_empty_series', true);

    contract.metrics = struct( ...
        'required_fields', {{'cases'}}, ...
        'case_required_fields', {{ ...
            'case_id', 'status', 'peak_abs_roll_deg', 'peak_abs_roll_rate_dps', ...
            'residual_roll_deg', 'all_finite'}}, ...
        'units', struct( ...
            'peak_abs_roll_deg', 'deg', ...
            'peak_abs_roll_rate_dps', 'deg/s', ...
            'residual_roll_deg', 'deg', ...
            'recovery_time_s', 's', ...
            'time_outside_band_s', 's', ...
            'max_heading_error_deg', 'deg', ...
            'max_depth_error_m', 'm', ...
            'rudder_saturation_pct', 'percent'));

    contract.screening = struct( ...
        'required_fields', {{ ...
            'execution_pass', 'screening_pass', 'thresholds'}}, ...
        'threshold_units', struct( ...
            'peak_abs_roll_deg', 'deg', ...
            'peak_abs_roll_rate_dps', 'deg/s', ...
            'residual_roll_deg', 'deg', ...
            'recovery_time_s', 's', ...
            'time_outside_band_s', 's', ...
            'rudder_saturation_pct', 'percent', ...
            'max_heading_error_deg', 'deg', ...
            'max_depth_error_m', 'm', ...
            'screening_band_deg', 'deg'));

    contract.provenance = struct( ...
        'required_fields', {{ ...
            'source_path', 'source_schema', 'normalized_utc', 'note'}}, ...
        'forbidden_claim_fields', {{'approved'}});

    contract.known_source_schemas = { ...
        'auv_v1_passive_roll_stress_v1', ...
        'auv_v1_roll_rate_solution_audit_v1'};
    out = contract;
end

function template = build_result_template()
    contract = auv_result_contract();
    template = struct();
    template.meta = struct( ...
        'schema', contract.schema, ...
        'contract_version', contract.version, ...
        'certified', false, ...
        'source_schema', '', ...
        'scenario', '', ...
        'mode', '', ...
        'seed', NaN, ...
        'artifact_kind', 'timeseries');

    template.time = struct('t_s', zeros(0, 1), 'dt_s', NaN, 'n_samples', 0);

    template.truth = struct( ...
        'position_ned_m', zeros(0, 3), ...
        'attitude_rad', zeros(0, 3), ...
        'velocity_body_mps', zeros(0, 3), ...
        'rates_body_rps', zeros(0, 3));

    template.sensors = struct( ...
        'attitude_rad', zeros(0, 3), ...
        'angular_rate_body_rps', zeros(0, 3), ...
        'depth_m', zeros(0, 1));

    template.commands = struct( ...
        'elevator_rad', zeros(0, 1), ...
        'rudder_rad', zeros(0, 1), ...
        'thrust_n', zeros(0, 1));

    template.actuators = struct( ...
        'applied_elevator_rad', zeros(0, 1), ...
        'applied_rudder_rad', zeros(0, 1));

    template.metrics = struct('cases', repmat(empty_metrics_case_row(), 0, 1));
    template.screening = struct( ...
        'execution_pass', false, ...
        'screening_pass', false, ...
        'thresholds', struct());
    template.provenance = struct( ...
        'source_path', '', ...
        'source_schema', '', ...
        'normalized_utc', '', ...
        'note', '');
end

function row = empty_metrics_case_row()
    row = struct( ...
        'case_id', '', ...
        'status', '', ...
        'shadow_id', '', ...
        'peak_abs_roll_deg', NaN, ...
        'peak_abs_roll_rate_dps', NaN, ...
        'residual_roll_deg', NaN, ...
        'all_finite', false);
end
